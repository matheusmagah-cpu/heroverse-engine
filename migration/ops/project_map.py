#!/usr/bin/env python3
"""Project map (owner, 2026-10-24: "create the project map; repeat it when it needs updating").

Builds, from the repository itself, what runs what: every workflow with its triggers and the scripts it calls, every
active Python module with its purpose (first docstring line), the local modules it imports, the workflows that call
it and its test, and the modules nothing reaches (candidates to archive). Rerun it after any structural change:

usage: project_map.py [REPO_ROOT] [OUT_DIR]     writes OUT_DIR/project-map.md and project-map.json
"""
import ast
import json
from pathlib import Path
import re
import sys

SKIP = ("archive", "__pycache__", ".claude")
CALL = re.compile(r"migration/[\w./-]+\.(?:py|sh)")
EVIDENCE = "migration/evidence/"   # slim audit 2026-10-28 (D9): evidence scripts are provenance, not orphans


def modules(root):
    out = {}
    for p in sorted((root / "migration").rglob("*.py")):
        rel = p.relative_to(root)
        if any(s in rel.parts for s in SKIP):
            continue
        try:
            tree = ast.parse(p.read_text())
        except (SyntaxError, UnicodeDecodeError):
            continue
        doc = (ast.get_docstring(tree) or "").strip().splitlines()
        imports = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imports |= {a.name.split(".")[0] for a in node.names}
            elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
                imports.add(node.module.split(".")[0])
        out[str(rel)] = {"purpose": doc[0] if doc else "", "imports": sorted(imports), "dir": str(rel.parent)}
    by_name = {}
    for rel in out:
        by_name.setdefault(Path(rel).stem, []).append(rel)
    for rel, m in out.items():  # resolve names to repository modules (same dir first, then anywhere)
        local = []
        for name in m["imports"]:
            cands = by_name.get(name, [])
            same = [c for c in cands if Path(c).parent == Path(rel).parent]
            if same or cands:
                local.append((same or cands)[0])
        m["local_imports"] = sorted(set(local) - {rel})
        del m["imports"]
    return out


def workflows(root):
    out = {}
    for p in sorted((root / ".github/workflows").glob("*.yml")):
        text = p.read_text()
        name = re.search(r"^name:\s*(.+)$", text, re.M)
        on = re.search(r"^on:\s*\n((?:[ \t]+.*\n)+)", text, re.M)
        triggers = sorted(set(re.findall(r"^\s{2}(\w+):", on.group(1), re.M))) if on else []
        cron = re.findall(r"cron:\s*'([^']+)'", text)
        dispatches = sorted(set(re.findall(r"(?:gh workflow run|workflow_id[\"']?:)\s*\"?([\w-]+\.yml)", text)))
        out[p.name] = {"name": name.group(1).strip() if name else p.name, "triggers": triggers, "cron": cron,
                       "calls": sorted(set(CALL.findall(text))), "dispatches": dispatches}
    return out


def build(root):
    root = Path(root)
    mods, wfs = modules(root), workflows(root)
    # E105: the parts relative to the repository, never the absolute path (an agent worktree is under .claude/)
    shell = {str(p.relative_to(root)): sorted(set(CALL.findall(p.read_text())))
             for p in (root / "migration").rglob("*.sh") if not any(s in p.relative_to(root).parts for s in SKIP)}
    called_by = {}
    for wf, w in wfs.items():
        for c in w["calls"]:
            called_by.setdefault(c, set()).add(wf)
            for c2 in shell.get(c, []):  # scripts run by a workflow's shell script
                called_by.setdefault(c2, set()).add(wf)
    imported_by = {}
    for rel, m in mods.items():
        for dep in m["local_imports"]:
            imported_by.setdefault(dep, set()).add(rel)
    for rel, m in mods.items():
        m["called_by_workflows"] = sorted(called_by.get(rel, set()))
        m["imported_by"] = sorted(imported_by.get(rel, set()))
        test = Path(rel).with_name("test_" + Path(rel).name)
        m["test"] = str(test) if str(test) in mods else None
        m["is_test"] = Path(rel).name.startswith("test_")
    reached = set()
    todo = [r for r, m in mods.items() if m["called_by_workflows"]]
    while todo:  # everything a workflow runs, directly or through imports
        r = todo.pop()
        if r in reached:
            continue
        reached.add(r)
        todo += mods[r]["local_imports"]
    # scripts under migration/evidence/ produced recorded evidence and stay as its provenance: never "candidates"
    orphans = sorted(r for r, m in mods.items() if not m["is_test"] and r not in reached and not m["imported_by"]
                     and not r.startswith(EVIDENCE))
    return {"version": "project-map-v1", "workflows": wfs, "shell": shell, "modules": mods,
            "unreached_by_any_workflow": orphans}


def markdown(m):
    lines = ["# HeroVerse project map", "", "Generated by `migration/ops/project_map.py` from the repository; rerun it to update.", "",
             "## Workflows (what runs, when, and what it calls)", "", "| workflow | triggers | calls | dispatches |", "|---|---|---|---|"]
    for wf, w in m["workflows"].items():
        trig = ", ".join(w["triggers"]) + (f" (cron {', '.join(w['cron'])})" if w["cron"] else "")
        calls = "<br>".join(c.replace("migration/", "") for c in w["calls"]) or "-"
        lines.append(f"| `{wf}` | {trig} | {calls} | {', '.join(w['dispatches']) or '-'} |")
    lines += ["", "## Flow", "", "```mermaid", "flowchart LR"]
    ids = {}
    def nid(x):
        return ids.setdefault(x, f"n{len(ids)}")
    for wf, w in m["workflows"].items():
        for d in w["dispatches"]:
            lines.append(f'  {nid(wf)}["{wf}"] --> {nid(d)}["{d}"]')
        for c in w["calls"]:
            if c.endswith(".sh") or "production" in c or "publish" in c:
                lines.append(f'  {nid(wf)}["{wf}"] -.-> {nid(c)}["{c.replace("migration/", "")}"]')
    lines += ["```", "", "## Modules by area", ""]
    for area in sorted({mm["dir"] for mm in m["modules"].values()}):
        lines += [f"### `{area}`", "", "| module | purpose | run by | imports | test |", "|---|---|---|---|---|"]
        for rel, mm in sorted(m["modules"].items()):
            if mm["dir"] != area or mm["is_test"]:
                continue
            lines.append(f"| `{Path(rel).name}` | {mm['purpose'][:110]} | {', '.join(mm['called_by_workflows']) or '-'} | "
                         f"{', '.join(Path(x).stem for x in mm['local_imports']) or '-'} | {'yes' if mm['test'] else '**no**'} |")
        lines.append("")
    lines += ["## Not reached by any workflow (directly or through imports)", "",
              "Run by hand, by the Claude clock, or candidates to archive:", ""]
    lines += [f"- `{r}`" for r in m["unreached_by_any_workflow"]] or ["- none"]
    return "\n".join(lines) + "\n"


def main(argv):
    root = Path(argv[0]) if argv else Path(__file__).resolve().parents[2]
    out = Path(argv[1]) if len(argv) > 1 else root / "migration/evidence/map"
    out.mkdir(parents=True, exist_ok=True)
    m = build(root)
    (out / "project-map.json").write_text(json.dumps(m, indent=1, ensure_ascii=False) + "\n")
    (out / "project-map.md").write_text(markdown(m))
    print(json.dumps({"workflows": len(m["workflows"]), "modules": len(m["modules"]),
                      "unreached": len(m["unreached_by_any_workflow"])}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
